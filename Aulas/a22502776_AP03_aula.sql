SELECT EMPLOYEE_ID, LAST_NAME, SALARY
FROM HR.EMPLOYEES
WHERE SALARY >= 12000
ORDER BY SALARY DESC;

SELECT EMPLOYEE_ID, DEPARTMENT_ID, SALARY
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID = 60
  AND SALARY > 9000
ORDER BY SALARY DESC;

SELECT EMPLOYEE_ID, DEPARTMENT_ID, JOB_ID
FROM HR.EMPLOYEES
WHERE (DEPARTMENT_ID = 50 OR DEPARTMENT_ID = 80)
    AND NOT (JOB_ID = 'SA_MAN');

SELECT EMPLOYEE_ID, SALARY
FROM HR.EMPLOYEES
WHERE SALARY BETWEEN 6000 AND 8000
ORDER BY SALARY, EMPLOYEE_ID;

SELECT EMPLOYEE_ID, HIRE_DATE
FROM HR.EMPLOYEES
WHERE HIRE_DATE NOT BETWEEN '20050101' AND '20051231'
ORDER BY HIRE_DATE;

SELECT EMPLOYEE_ID, LAST_NAME
FROM HR.EMPLOYEES
WHERE LAST_NAME LIKE 'M%'
ORDER BY LAST_NAME;

SELECT EMPLOYEE_ID, LAST_NAME
FROM HR.EMPLOYEES
WHERE LAST_NAME LIKE '__a%'
ORDER BY LAST_NAME;

SELECT EMPLOYEE_ID, JOB_ID
FROM HR.EMPLOYEES
WHERE JOB_ID LIKE '%!_%' ESCAPE '!'
ORDER BY EMPLOYEE_ID;

SELECT EMPLOYEE_ID, DEPARTMENT_ID
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IN (20, 40, 70)
ORDER BY DEPARTMENT_ID, EMPLOYEE_ID;

SELECT EMPLOYEE_ID, JOB_ID
FROM HR.EMPLOYEES
WHERE JOB_ID NOT IN ('AD_PRES', 'AD_VP')
ORDER BY EMPLOYEE_ID;

SELECT EMPLOYEE_ID, LAST_NAME, MANAGER_ID
FROM HR.EMPLOYEES
WHERE MANAGER_ID IS NULL;

SELECT EMPLOYEE_ID, DEPARTMENT_ID
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IS NULL;

SELECT EMPLOYEE_ID, LAST_NAME, DEPARTMENT_ID
FROM HR.EMPLOYEES
WHERE LAST_NAME LIKE 'S%'
  AND DEPARTMENT_ID BETWEEN 20 AND 50
ORDER BY LAST_NAME;

SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME
FROM HR.EMPLOYEES
WHERE (FIRST_NAME LIKE '%A%' AND FIRST_NAME LIKE '%Z%')
   OR (LAST_NAME LIKE '%A%' AND LAST_NAME LIKE '%Z%')
ORDER BY EMPLOYEE_ID;

SELECT EMPLOYEE_ID, LAST_NAME
FROM HR.EMPLOYEES
WHERE LAST_NAME LIKE '[RST]%'
ORDER BY LAST_NAME;

SELECT EMPLOYEE_ID, LAST_NAME
FROM HR.EMPLOYEES
WHERE LAST_NAME LIKE '__[AEIOU]%'
ORDER BY LAST_NAME;

SELECT EMPLOYEE_ID, JOB_ID
FROM HR.EMPLOYEES
WHERE JOB_ID LIKE '[AF]_[A-Z]%'
ORDER BY EMPLOYEE_ID;

SELECT EMPLOYEE_ID, PHONE_NUMBER
FROM HR.EMPLOYEES
WHERE PHONE_NUMBER LIKE '%[^0-9.]%';

SELECT EMPLOYEE_ID, LAST_NAME
FROM HR.EMPLOYEES
WHERE LAST_NAME LIKE '[A-Z]%'
    AND LAST_NAME LIKE '%[^A-Z''-]%';

SELECT EMPLOYEE_ID, EMAIL
FROM HR.EMPLOYEES
WHERE EMAIL NOT LIKE '%[^A-Z0-9]%'
ORDER BY EMPLOYEE_ID;

DECLARE @password VARCHAR(100) = 'DbCourse9!';

SELECT @password AS password_candidate,
       CASE WHEN LEN(@password) >= 8
                  AND @password LIKE '%[A-Z]%'
                  AND @password LIKE '%[a-z]%'
                  AND @password LIKE '%[0-9]%'
                  AND @password LIKE '%[^A-Za-z0-9]%'
            THEN 'Compliant' ELSE 'Not compliant'
       END AS password_status;

SELECT EMPLOYEE_ID, JOB_ID,
    CASE JOB_ID
        WHEN 'AD_PRES' THEN 'Executive'
        WHEN 'AD_VP' THEN 'Executive'
        ELSE 'Other role'
    END AS job_group
FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, SALARY,
    CASE
        WHEN SALARY >= 12000 THEN 'High'
        WHEN SALARY >= 6000 THEN 'Medium'
        ELSE 'Entry'
    END AS salary_band
FROM HR.EMPLOYEES
ORDER BY SALARY DESC;

SELECT EMPLOYEE_ID, COMMISSION_PCT,
    CASE
        WHEN COMMISSION_PCT IS NULL THEN 'Not commission-based'
        ELSE 'Commission-based'
    END AS pay_model
FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, MANAGER_ID,
    IIF(MANAGER_ID IS NULL, 'Top level', 'Reports to manager') AS reporting_status
FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, SALARY, COMMISSION_PCT,
    IIF(COMMISSION_PCT IS NULL,
        SALARY,
        SALARY * (1 + COMMISSION_PCT)) AS projected_pay
FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, COMMISSION_PCT,
    CASE
        WHEN COMMISSION_PCT IS NULL THEN 'None'
        WHEN COMMISSION_PCT < 0.2 THEN 'Standard'
        ELSE 'Enhanced'
    END AS commission_band
FROM HR.EMPLOYEES;