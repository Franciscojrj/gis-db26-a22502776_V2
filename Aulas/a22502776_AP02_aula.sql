USE ULHT_DB26;
GO

Select *
from HR.EMPLOYEES;

SELECT EMPLOYEE_ID,
    CONCAT(FIRST_NAME, ' ', LAST_NAME) AS FULL_NAME,
    LOWER(CONCAT(LEFT(FIRST_NAME, 1), '.', LAST_NAME)) AS login_name
FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, SALARY,
  SALARY * 12 AS annual_salary,
  SALARY * 1.05 AS salary_after_raise
FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, HIRE_DATE,
  DATEADD(YEAR, 1, HIRE_DATE) AS first_anniversary,
  DATEDIFF(YEAR, HIRE_DATE, GETDATE()) AS year_boundaries
FROM HR.EMPLOYEES;

SELECT TOP (5) EMPLOYEE_id, sALARY,
  SALARY * 12 AS annual_salary,
  SQL_VARIANT_PROPERTY(SALARY * 12, 'BaseType') AS result_type
FROM HR.EMPLOYEES
ORDER BY EMPLOYEE_ID DESC;

SELECT EMPLOYEE_ID, COMMISSION_PCT
FROM HR.EMPLOYEES
WHERE COMMISSION_PCT IS NULL;

SELECT EMPLOYEE_ID, SALARY, COMMISSION_PCT,
  SALARY * (1 + ISNULL(COMMISSION_PCT, 0)) AS total_pay
FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID,
  COALESCE(PHONE_NUMBER, EMAIL, 'No contact') AS contact
FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, SALARY, COMMISSION_PCT,
  ISNULL(COMMISSION_PCT, 0) AS commission_rate
FROM HR.EMPLOYEES
WHERE COMMISSION_PCT IS NULL;

SELECT EMPLOYEE_ID,
  CONCAT('EMP-', CAST(EMPLOYEE_ID AS VARCHAR(10))) AS employee_code
FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID,
  CONVERT(CHAR(10), HIRE_DATE, 23) AS hire_date_text
FROM HR.EMPLOYEES;

SELECT TRY_CONVERT(INT, '2703') AS valid_number,
  TRY_CONVERT(INT, '2703') AS invalid_number;

SELECT SQL_VARIANT_PROPERTY(CAST(EMPLOYEE_ID AS VARCHAR(10)), 'BaseType') AS base_type,
  SQL_VARIANT_PROPERTY(CAST(EMPLOYEE_ID AS VARCHAR(10)), 'MaxLength') AS max_length
FROM HR.EMPLOYEES
WHERE EMPLOYEE_ID = 100;

SELECT EMPLOYEE_ID, SALARY,
  FORMAT(SALARY, 'C', 'en-GB') AS salary_display
FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, HIRE_DATE,
  FORMAT(HIRE_DATE, 'dd MMM yyyy') AS hire_date_display
FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID,
  RIGHT(REPLICATE('0', 6) + CAST(EMPLOYEE_ID AS VARCHAR(6)), 6) AS padded_id
FROM HR.EMPLOYEES;

SELECT TOP (5) EMPLOYEE_ID, SALARY,
  FORMAT(SALARY, 'N2', 'en-GB') AS salary_display
FROM HR.EMPLOYEES
ORDER BY SALARY DESC;

