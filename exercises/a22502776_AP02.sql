  FIRST_NAME + ' ' + LAST_NAME AS full_name,
  CONVERT(CHAR(10), HIRE_DATE, 23) AS iso_hire_date,
  FORMAT(SALARY * 14 * (1 + ISNULL(COMMISSION_PCT, 0)), 'C2', 'pt-PT') AS annual_salary_display,
